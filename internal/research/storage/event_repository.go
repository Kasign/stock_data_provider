package storage

import (
	"context"
	"database/sql"
	"encoding/json"
	"fmt"

	researchevent "example.com/stock-analysis-flow/internal/research/event"
)

const eventTable = "research_event_versions"

type EventRepository struct{ base repositoryBase }

func NewEventRepository(db *sql.DB, clock Clock) (*EventRepository, error) {
	base, err := newRepositoryBase(db, clock)
	if err != nil {
		return nil, err
	}
	return &EventRepository{base: base}, nil
}

var _ researchevent.Repository = (*EventRepository)(nil)

func (r *EventRepository) Append(ctx context.Context, value researchevent.ResearchEvent) error {
	if r == nil {
		return ErrInvalidRepository
	}
	if err := value.Validate(); err != nil {
		return fmt.Errorf("validate Event: %w", err)
	}
	payload, digest, err := encodePayload(value)
	if err != nil {
		return err
	}
	now := r.base.now().UTC()
	insert := "INSERT INTO research_event_versions (event_id, event_version, status, system_as_of, payload_sha256, payload, created_at) VALUES (?, ?, ?, ?, ?, ?, ?)"
	return r.base.appendVersionWithHooks(ctx, "event", value.EventID, int64(value.EventVersion),
		eventTable, "event_id", "event_version", payload, now, insert,
		[]any{value.EventID, value.EventVersion, string(value.Status), formatPIT(value.SystemAsOf), digest, string(payload), now},
		func(previous []byte) error {
			var prior researchevent.ResearchEvent
			if err := json.Unmarshal(previous, &prior); err != nil {
				return fmt.Errorf("decode previous Event: %w", err)
			}
			return value.ValidateNextVersion(prior)
		},
		func(tx *sql.Tx, _ []byte) error { return validateEventDerivedRefs(ctx, tx, value) },
		nil)
}

// AppendWithLifecycle atomically appends an Event version and its
// Notification Outbox envelope. correlationID must come from trusted context
// or be generated by the Application layer.
func (r *EventRepository) AppendWithLifecycle(ctx context.Context, value researchevent.ResearchEvent, reasonCode *string, correlationID string) error {
	if r == nil {
		return ErrInvalidRepository
	}
	if err := value.Validate(); err != nil {
		return fmt.Errorf("validate Event: %w", err)
	}
	if !validCorrelationID(correlationID) {
		return fmt.Errorf("trusted correlation ID is required")
	}
	if reasonCode != nil && !validCorrelationID(*reasonCode) {
		return fmt.Errorf("reason_code must be null or a non-empty trimmed value")
	}
	payload, digest, err := encodePayload(value)
	if err != nil {
		return err
	}
	now := r.base.now().UTC()
	if now.IsZero() {
		return fmt.Errorf("repository clock returned zero time")
	}
	insert := "INSERT INTO research_event_versions (event_id, event_version, status, system_as_of, payload_sha256, payload, created_at) VALUES (?, ?, ?, ?, ?, ?, ?)"
	var previous researchevent.ResearchEvent
	return r.base.appendVersionWithHooks(ctx, "event", value.EventID, int64(value.EventVersion),
		eventTable, "event_id", "event_version", payload, now, insert,
		[]any{value.EventID, value.EventVersion, string(value.Status), formatPIT(value.SystemAsOf), digest, string(payload), now},
		func(raw []byte) error {
			if len(raw) == 0 {
				if value.EventVersion != 1 {
					return fmt.Errorf("first lifecycle Outbox Event must be version 1")
				}
				return nil
			}
			if err := json.Unmarshal(raw, &previous); err != nil {
				return fmt.Errorf("decode previous Event: %w", err)
			}
			return value.ValidateNextVersion(previous)
		},
		func(tx *sql.Tx, _ []byte) error {
			return validateEventDerivedRefs(ctx, tx, value)
		},
		func(tx *sql.Tx, previousPayload []byte) error {
			if len(previousPayload) == 0 {
				return insertResearchLifecycleCreatedOutbox(ctx, tx, value, reasonCode, correlationID, now)
			}
			transition, err := researchevent.NewLifecycleTransition(previous, value, now)
			if err != nil {
				return err
			}
			if transition == nil {
				return fmt.Errorf("lifecycle Outbox requires a status change")
			}
			return insertResearchLifecycleOutbox(ctx, tx, previous, value, *transition, reasonCode, correlationID, now)
		})
}

func (r *EventRepository) GetVersion(ctx context.Context, id string, version int) (researchevent.ResearchEvent, error) {
	if r == nil {
		return researchevent.ResearchEvent{}, ErrInvalidRepository
	}
	var value researchevent.ResearchEvent
	payload, err := r.base.getVersion(ctx, eventTable, "event_id", "event_version", id, int64(version))
	if err != nil {
		return value, err
	}
	if err := json.Unmarshal(payload, &value); err != nil {
		return value, corruptStoredRecord("Event", "decode failed", err)
	}
	if err := value.Validate(); err != nil {
		return value, corruptStoredRecord("Event", "validation failed", err)
	}
	if value.EventID != id || value.EventVersion != version {
		return value, corruptStoredIdentity("Event")
	}
	return value, nil
}


// validateEventDerivedRefs resolves every exact Event version in the same
// transaction as the append. This prevents a concurrent or missing reference
// from being accepted between validation and persistence.
func validateEventDerivedRefs(ctx context.Context, tx *sql.Tx, value researchevent.ResearchEvent) error {
	visited := make(map[researchevent.ResearchEventRef]struct{})
	visiting := make(map[researchevent.ResearchEventRef]struct{})
	var visit func(researchevent.ResearchEventRef) error
	visit = func(ref researchevent.ResearchEventRef) error {
		if _, ok := visiting[ref]; ok {
			return fmt.Errorf("derived_from_refs contains a cycle at %s@%d", ref.EventID, ref.EventVersion)
		}
		if _, ok := visited[ref]; ok {
			return nil
		}
		visiting[ref] = struct{}{}
		var digest string
		var payload []byte
		err := tx.QueryRowContext(ctx,
			"SELECT payload_sha256, payload FROM research_event_versions WHERE event_id=? AND event_version=?",
			ref.EventID, ref.EventVersion,
		).Scan(&digest, &payload)
		if err != nil {
			if err == sql.ErrNoRows {
				return fmt.Errorf("%w: derived Event reference %s@%d does not exist", ErrNotFound, ref.EventID, ref.EventVersion)
			}
			return fmt.Errorf("read derived Event reference %s@%d: %w", ref.EventID, ref.EventVersion, err)
		}
		if err := verifyStoredPayload(payload, digest); err != nil {
			return err
		}
		var referenced researchevent.ResearchEvent
		if err := json.Unmarshal(payload, &referenced); err != nil {
			return corruptStoredRecord("Event", "derived reference decode failed", err)
		}
		if referenced.EventID != ref.EventID || referenced.EventVersion != ref.EventVersion {
			return corruptStoredIdentity("Event derived reference")
		}
		if err := referenced.Validate(); err != nil {
			return corruptStoredRecord("Event", "derived reference validation failed", err)
		}
		for _, parent := range referenced.DerivedFromRefs {
			if err := visit(parent); err != nil {
				return err
			}
		}
		delete(visiting, ref)
		visited[ref] = struct{}{}
		return nil
	}
	for _, ref := range value.DerivedFromRefs {
		if ref.EventID == value.EventID && ref.EventVersion == value.EventVersion {
			return fmt.Errorf("Event cannot derive from itself")
		}
		if err := visit(ref); err != nil {
			return err
		}
	}
	return nil
}
